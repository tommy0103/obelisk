export const DEFAULT_EVAL_POLICY = Object.freeze({
  contextWindow: 200_000,
  normalBudget: 160_000,
  reminderThresholdTokens: 24_000,
  fallbackReserveTokens: 24_000,
  outputReserveTokens: 16_000,
  compactRetainTokens: 32_000,
  compactSummaryMaxTokens: 16_000,
});

function positiveInteger(name, value) {
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new TypeError(`${name} must be a positive safe integer`);
  }
}

export function validatePolicy(policy) {
  for (const [name, value] of Object.entries(policy)) positiveInteger(name, value);
  const derivedNormalBudget = policy.contextWindow
    - policy.outputReserveTokens
    - policy.fallbackReserveTokens;
  if (derivedNormalBudget !== policy.normalBudget) {
    throw new TypeError(
      `normalBudget must equal contextWindow - outputReserveTokens - fallbackReserveTokens (${derivedNormalBudget})`,
    );
  }
  if (policy.compactRetainTokens >= policy.normalBudget) {
    throw new TypeError('compactRetainTokens must be smaller than normalBudget');
  }
  return policy;
}

function yamlString(value) {
  return JSON.stringify(value);
}

export function buildArmPatch({
  arm,
  sessionsRoot,
  model = 'deepseek-v4-flash',
  policy = DEFAULT_EVAL_POLICY,
}) {
  validatePolicy(policy);
  if (arm !== 'compact' && arm !== 'rollover') {
    throw new TypeError(`unknown eval arm ${JSON.stringify(arm)}`);
  }
  if (typeof sessionsRoot !== 'string' || sessionsRoot.length === 0) {
    throw new TypeError('sessionsRoot must be a non-empty string');
  }
  const common = [
    '# Generated by scripts/context-window-ab-eval.mjs.',
    '- id: llm-deepseek',
    '  config:',
    '    models:',
    `      - id: ${yamlString(model)}`,
    `        contextWindow: ${policy.contextWindow}`,
    '',
    '- id: session-title-llm',
    '  disabled: true',
    '',
    '- id: session-persistence-jsonl',
    '  config:',
    `    root: ${yamlString(sessionsRoot)}`,
    '    compression: none',
    '',
    '- id: compaction-basic',
    '  config:',
  ];
  if (arm === 'compact') {
    return `${[
      ...common,
      '    auto: true',
      `    thresholdRatio: ${policy.normalBudget / policy.contextWindow}`,
      `    retainTokens: ${policy.compactRetainTokens}`,
      `    maxTokens: ${policy.compactSummaryMaxTokens}`,
      '    compactionRetries: 1',
      '    maxOverflowRetries: 1',
      '',
    ].join('\n')}`;
  }
  return `${[
    ...common,
    '    auto: false',
    '',
    '- insert:',
    '    - id: obelisk-context-window',
    "      name: '@obelisk/dsh-obelisk-plugin/context-window'",
    '      config:',
    `        reminderThresholdTokens: ${policy.reminderThresholdTokens}`,
    `        fallbackReserveTokens: ${policy.fallbackReserveTokens}`,
    `        outputReserveTokens: ${policy.outputReserveTokens}`,
    '',
  ].join('\n')}`;
}

export function parseSessionJsonl(text) {
  return text
    .split(/\r?\n/u)
    .filter(line => line.trim() !== '')
    .map((line, index) => {
      try {
        return JSON.parse(line);
      } catch (error) {
        throw new SyntaxError(`invalid session JSON at line ${index + 1}: ${String(error)}`, { cause: error });
      }
    });
}

function usageTotals(events) {
  const totals = {
    inputTokens: 0,
    outputTokens: 0,
    reasoningTokens: 0,
    cacheReadTokens: 0,
    cacheWriteTokens: 0,
    totalTokens: 0,
  };
  for (const event of events) {
    if (event.type !== 'assistant/message' && event.type !== 'compaction/summary') continue;
    const usage = event.data?.usage;
    if (typeof usage !== 'object' || usage === null) continue;
    for (const key of Object.keys(totals).filter(key => key !== 'totalTokens')) {
      const value = usage[key];
      if (typeof value === 'number' && Number.isFinite(value)) totals[key] += value;
    }
    const reportedTotal = usage.totalTokens;
    totals.totalTokens += typeof reportedTotal === 'number' && Number.isFinite(reportedTotal)
      ? reportedTotal
      : (usage.inputTokens ?? 0)
        + (usage.cacheReadTokens ?? 0)
        + (usage.cacheWriteTokens ?? 0)
        + (usage.outputTokens ?? 0);
  }
  return totals;
}

function bashCommand(event) {
  if (event.type !== 'tool/call' || event.data?.name !== 'bash') return undefined;
  try {
    const args = JSON.parse(event.data.arguments);
    return typeof args.command === 'string' ? args.command : undefined;
  } catch {
    return undefined;
  }
}

export function summarizeSession(events) {
  const toolCalls = events.filter(event => event.type === 'tool/call');
  const bashCommands = toolCalls.map(bashCommand).filter(Boolean);
  const uniqueBashCommands = new Set(bashCommands);
  const pressure = events.filter(event =>
    event.type === 'user/message'
    && event.data?.source?.kind === 'obelisk-context-pressure');
  const handoffs = events.filter(event =>
    event.type === 'user/message'
    && event.data?.source?.kind === 'obelisk-context-handoff');
  const turnEnds = events.filter(event => event.type === 'turn/end');
  const finalReason = turnEnds.at(-1)?.data?.reason;
  const usage = usageTotals(events);
  const observedContextWindows = [...new Set(events
    .filter(event => event.type === 'request/context')
    .map(event => event.data?.contextWindow)
    .filter(value => Number.isSafeInteger(value) && value > 0))];
  const completedCompactions = events.filter(event => event.type === 'compaction/summary').length;
  const completedRollovers = handoffs.length;
  return {
    events: events.length,
    requests: events.filter(event => event.type === 'request/context').length,
    steps: events.filter(event => event.type === 'step/start').length,
    toolCalls: toolCalls.length,
    bashCalls: bashCommands.length,
    repeatedBashCalls: bashCommands.length - uniqueBashCommands.size,
    obeliskCalls: bashCommands.filter(command => /(^|[;&|\s])obelisk(?:\s|$)/u.test(command)).length,
    compaction: {
      starts: events.filter(event => event.type === 'compaction/start').length,
      summaries: events.filter(event => event.type === 'compaction/summary').length,
      ends: events.filter(event => event.type === 'compaction/end').length,
    },
    rollover: {
      reminders: pressure.filter(event => event.data.source.phase === 'reminder').length,
      fallbacks: pressure.filter(event => event.data.source.phase === 'fallback').length,
      handoffs: handoffs.length,
      modelRequested: handoffs.filter(event => event.data.source.trigger?.kind === 'model').length,
      forced: handoffs.filter(event => event.data.source.trigger?.kind === 'hard-limit').length,
      missingHandoffs: handoffs.filter(event => event.data.source.handoffStatus === 'missing').length,
    },
    usage,
    observedContextWindows,
    totalProviderTokens: usage.totalTokens,
    policyBoundaries: completedCompactions + completedRollovers,
    completed: finalReason?.kind === 'completed',
    finalReason: finalReason?.kind ?? null,
    errorTurns: turnEnds.filter(event => event.data?.reason?.kind === 'error').length,
    toolErrors: events.filter(event =>
      event.type === 'tool/result'
      && event.data?.message?.content?.some?.(block => block.isError === true)).length,
  };
}

export function qualifyRun(metrics, minimumContextWindow = DEFAULT_EVAL_POLICY.contextWindow) {
  const crossedAtLeastTwoBoundaries = metrics.policyBoundaries >= 2;
  const reachedMinimumProviderUsage = metrics.totalProviderTokens >= 450_000;
  const observedRequiredContext = metrics.observedContextWindows.length > 0
    && metrics.observedContextWindows.every(value => value >= minimumContextWindow);
  return {
    crossedAtLeastTwoBoundaries,
    reachedMinimumProviderUsage,
    observedRequiredContext,
    eligible: crossedAtLeastTwoBoundaries && reachedMinimumProviderUsage && observedRequiredContext,
  };
}
